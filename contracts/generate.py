# Writes the Go and Python enumerations from contracts/enums.yaml, so the 22 closed sets are typed once (C07).

import argparse
import sys
from pathlib import Path

import yaml

_ROOT = Path(__file__).resolve().parent.parent
_CONTRACT = _ROOT / "contracts" / "enums.yaml"
_GO_TARGET = _ROOT / "src" / "core" / "internal" / "platform" / "enums" / "enums_gen.go"
_PY_TARGET = _ROOT / "src" / "brain" / "infra" / "enums.py"

_BANNER = "Code generated by contracts/generate.py from contracts/enums.yaml. DO NOT EDIT."


def _pascal(value: str) -> str:
    return "".join(part.capitalize() for part in value.split("_"))


# A defined string type per enumeration, so the compiler stops a ContactType handed to a ConversationStatus.
def _render_go(contract: dict) -> str:
    lines = [f"// {_BANNER}", "", "package enums", "", 'import "slices"']

    for name, body in contract["enums"].items():
        values = [str(value) for value in body["values"]]
        constants = [f"{name}{_pascal(value)}" for value in values]

        lines += ["", f"// {name} is declared by {body['origin']}.", f"type {name} string", "", "const ("]
        # Padded because gofmt aligns a const block, and generated code that gofmt would rewrite fails the CI check.
        width = max(len(constant) for constant in constants)
        lines += [f'\t{constant:<{width}} {name} = "{value}"' for constant, value in zip(constants, values)]
        lines += [
            ")",
            "",
            f"// {name}Values holds the declared values, in the order of the contract.",
            f"var {name}Values = []{name}{{{', '.join(constants)}}}",
            "",
            "// IsValid reports whether the value is one the contract declares.",
            f"func (v {name}) IsValid() bool {{",
            f"\treturn slices.Contains({name}Values, v)",
            "}",
        ]

    return "\n".join(lines) + "\n"


# StrEnum and not plain constants, so a value compares as a string and still fails a membership check when it is wrong.
def _render_python(contract: dict) -> str:
    lines = [f"# {_BANNER}", "", "from enum import StrEnum"]

    for name, body in contract["enums"].items():
        lines += ["", "", f"# {name} is declared by {body['origin']}.", f"class {name}(StrEnum):"]
        lines += [f'    {str(value).upper()} = "{value}"' for value in body["values"]]

    return "\n".join(lines) + "\n"


# Reports what is stale instead of writing, so the CI can fail a commit whose generated files were never regenerated.
def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(prog="generate")
    parser.add_argument("--check", action="store_true", help="falla si lo generado quedo viejo, sin escribir nada")
    args = parser.parse_args(argv)

    contract = yaml.safe_load(_CONTRACT.read_text(encoding="utf-8"))
    outputs = {_GO_TARGET: _render_go(contract), _PY_TARGET: _render_python(contract)}

    if args.check:
        stale = [path for path, content in outputs.items() if not path.exists() or path.read_text(encoding="utf-8") != content]
        for path in stale:
            print(f"out of date: {path.relative_to(_ROOT).as_posix()}", file=sys.stderr)
        return 1 if stale else 0

    for path, content in outputs.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8", newline="\n")
        print(f"wrote {path.relative_to(_ROOT).as_posix()}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
