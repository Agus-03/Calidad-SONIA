// TestCreateRefusesANameThatIsOnlyBlanks is why the service validates at all: the column is NOT NULL and spaces satisfy it.
func TestCreateRefusesANameThatIsOnlyBlanks(t *testing.T) {
	ctx := context.Background()
	store := newStubStore()
	service := NewService(store, nil)
	account, operator := id.New(), id.New()

	for _, name := range []string{"", "   ", "\t\n"} {
		if _, err := service.Create(ctx, account, operator, name, "#112233"); !errors.Is(err, ErrEmptyName) {
			t.Fatalf("Create(%q): got %v, want ErrEmptyName", name, err)
		}
	}
	if len(store.rows) != 0 {
		t.Fatalf("the store holds %d rows, want the blank name never to have reached it", len(store.rows))
	}
}

// TestCreateStampsTheIdAndWhoCreatedIt protects C04 and the seam: the caller sends neither, and both end up on the row.
func TestCreateStampsTheIdAndWhoCreatedIt(t *testing.T) {
	ctx := context.Background()
	service := NewService(newStubStore(), nil)
	account, operator := id.New(), id.New()

	label, err := service.Create(ctx, account, operator, "  Ventas  ", "#112233")
	if err != nil {
		t.Fatalf("Create: %v", err)
	}
	if label.ID == uuid.Nil {
		t.Fatalf("the label came back without an id, want one generated by the application")
	}
	if label.AccountID != account || label.CreatedByOperatorID != operator {
		t.Fatalf("the label is %+v, want the account and operator of the actor", label)
	}
	if label.Name != "Ventas" {
		t.Fatalf("stored name = %q, want the trimmed %q", label.Name, "Ventas")
	}
}

// TestCreateReportsANameAlreadyTaken keeps the casing rule alive above the repository, where the controller turns it into a 409.
func TestCreateReportsANameAlreadyTaken(t *testing.T) {
	ctx := context.Background()
	service := NewService(newStubStore(), nil)
	account, operator := id.New(), id.New()

	if _, err := service.Create(ctx, account, operator, "Ventas", "#112233"); err != nil {
		t.Fatalf("Create: %v", err)
	}
	if _, err := service.Create(ctx, account, operator, "ventas", "#445566"); !errors.Is(err, ErrDuplicateName) {
		t.Fatalf("the same name in another casing: got %v, want ErrDuplicateName", err)
	}
}

// TestUpdateAnswersTheRowAsItNowStands is why it reads back: the repository reports what changed and not what the row says afterwards.
func TestUpdateAnswersTheRowAsItNowStands(t *testing.T) {
	ctx := context.Background()
	service := NewService(newStubStore(), nil)
	account, operator := id.New(), id.New()

	created, err := service.Create(ctx, account, operator, "Segimiento", "#112233")
	if err != nil {
		t.Fatalf("Create: %v", err)
	}

	updated, err := service.Update(ctx, account, created.ID, "Seguimiento", "#445566")
	if err != nil {
		t.Fatalf("Update: %v", err)
	}
	if updated.Name != "Seguimiento" || updated.Color != "#445566" {
		t.Fatalf("the label came back as %+v, want the corrected name and color", updated)
	}
	if updated.ID != created.ID || updated.CreatedByOperatorID != operator {
		t.Fatalf("the label changed identity: %+v", updated)
	}
}

// TestUpdateAndDeleteOfAnUnknownLabelAreNotFound is the branch the controller turns into a 404 instead of a silent success.
func TestUpdateAndDeleteOfAnUnknownLabelAreNotFound(t *testing.T) {
	ctx := context.Background()
	service := NewService(newStubStore(), nil)
	account := id.New()

	if _, err := service.Update(ctx, account, id.New(), "Cualquiera", "#112233"); !errors.Is(err, ErrNotFound) {
		t.Fatalf("Update of an unknown label: got %v, want ErrNotFound", err)
	}
	if err := service.Delete(ctx, account, id.New()); !errors.Is(err, ErrNotFound) {
		t.Fatalf("Delete of an unknown label: got %v, want ErrNotFound", err)
	}
}

// TestUpdateRefusesABlankNameBeforeTouchingTheRow guards the case a create test cannot: here the row exists and would be left nameless.
func TestUpdateRefusesABlankNameBeforeTouchingTheRow(t *testing.T) {
	ctx := context.Background()
	store := newStubStore()
	service := NewService(store, nil)
	account, operator := id.New(), id.New()

	created, err := service.Create(ctx, account, operator, "Urgente", "#112233")
	if err != nil {
		t.Fatalf("Create: %v", err)
	}

	if _, err := service.Update(ctx, account, created.ID, "   ", "#445566"); !errors.Is(err, ErrEmptyName) {
		t.Fatalf("Update with a blank name: got %v, want ErrEmptyName", err)
	}
	if store.rows[0].Name != "Urgente" {
		t.Fatalf("the row now reads %q, want it untouched", store.rows[0].Name)
	}
}

// TestListOnlyReachesTheCallersAccount is the property every read of this phase rests on, checked once here and once against real SQL.
func TestListOnlyReachesTheCallersAccount(t *testing.T) {
	ctx := context.Background()
	mine, theirs := id.New(), id.New()
	store := newStubStore(
		Label{ID: id.New(), AccountID: mine, Name: "Mia", Color: "#112233", CreatedByOperatorID: id.New()},
		Label{ID: id.New(), AccountID: theirs, Name: "Ajena", Color: "#112233", CreatedByOperatorID: id.New()},
	)
	service := NewService(store, nil)

	page, err := service.List(ctx, mine, 20, 0)
	if err != nil {
		t.Fatalf("List: %v", err)
	}
	if page.Total != 1 || len(page.Items) != 1 || page.Items[0].Name != "Mia" {
		t.Fatalf("the page is %+v, want only the label of the calling account", page)
	}
}
